using Npgsql;
using Pgvector.Npgsql;

namespace Api.Servicios;

public static class BaseVectorial
{
    private const string PuertoPostgresPorDefecto = "5432";

    public static NpgsqlDataSource CrearConexion()
    {
        var host = Environment.GetEnvironmentVariable("DB_HOST");
        var puerto = Environment.GetEnvironmentVariable("DB_PORT");
        if (puerto is null)
        {
            puerto = PuertoPostgresPorDefecto;
        }

        var baseDeDatos = Environment.GetEnvironmentVariable("DB_NAME");
        var usuario = Environment.GetEnvironmentVariable("DB_USER");
        var contrasena = Environment.GetEnvironmentVariable("DB_PASSWORD");
        var cadenaDeConexion = "Host=" + host + ";Port=" + puerto + ";Database=" + baseDeDatos +
            ";Username=" + usuario + ";Password=" + contrasena;

        var constructor = new NpgsqlDataSourceBuilder(cadenaDeConexion);
        constructor.UseVector();
        return constructor.Build();
    }

    public static async Task PrepararTablasAsync(NpgsqlDataSource baseDatos, CancellationToken cancellationToken)
    {
        await using var conexion = await baseDatos.OpenConnectionAsync(cancellationToken);
        await using var comando = new NpgsqlCommand("""
            CREATE EXTENSION IF NOT EXISTS vector;
            CREATE SCHEMA IF NOT EXISTS vectorial;
            CREATE TABLE IF NOT EXISTS vectorial.documentos (
                id BIGSERIAL PRIMARY KEY,
                nombre TEXT NOT NULL,
                huella TEXT NOT NULL,
                version_proceso TEXT NOT NULL,
                procesado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
            );
            CREATE TABLE IF NOT EXISTS vectorial.fragmentos (
                id BIGSERIAL PRIMARY KEY,
                documento_id BIGINT NOT NULL REFERENCES vectorial.documentos(id) ON DELETE CASCADE,
                posicion INTEGER NOT NULL,
                pagina INTEGER NOT NULL,
                texto TEXT NOT NULL,
                embedding VECTOR(1024) NOT NULL,
                texto_busqueda TSVECTOR GENERATED ALWAYS AS (to_tsvector('spanish', texto)) STORED,
                UNIQUE(documento_id, posicion)
            );
            CREATE INDEX IF NOT EXISTS fragmentos_documento_idx
                ON vectorial.fragmentos(documento_id);
            CREATE INDEX IF NOT EXISTS fragmentos_texto_idx
                ON vectorial.fragmentos USING gin(texto_busqueda);
            CREATE TABLE IF NOT EXISTS vectorial.documento_tecnico (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nombre_archivo VARCHAR(255) NOT NULL,
                activo_id BIGINT,
                usa_sugerencias_ia BOOLEAN NOT NULL,
                cantidad_fragmentos INTEGER NOT NULL DEFAULT 0,
                archivo BYTEA NOT NULL,
                texto TEXT NOT NULL DEFAULT '',
                creado_en TIMESTAMPTZ NOT NULL,
                documento_vectorial_id BIGINT,
                titulo VARCHAR(200),
                tipo VARCHAR(30) NOT NULL DEFAULT 'manual_tecnico',
                descripcion TEXT,
                vigente BOOLEAN NOT NULL DEFAULT TRUE,
                modelo_maquina_id BIGINT,
                CONSTRAINT "CK_DOCUMENTO_TECNICO_TIPO" CHECK (tipo IN
                    ('normativa', 'procedimiento_interno', 'manual_tecnico', 'politica_seguridad', 'otro'))
            );
            ALTER TABLE vectorial.documento_tecnico
                ADD COLUMN IF NOT EXISTS documento_vectorial_id BIGINT;
            """, conexion);
        await comando.ExecuteNonQueryAsync(cancellationToken);
        await conexion.ReloadTypesAsync(cancellationToken);
    }
}

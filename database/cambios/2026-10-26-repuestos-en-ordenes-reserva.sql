-- Cantidad de cada repuesto en una orden y su ciclo: reservado (al asignarlo) -> entregado (cuando la orden entra en
-- progreso) -> descontado (al cerrar la orden, que es cuando baja el stock de verdad). Si la orden se elimina o se quita
-- el repuesto, queda liberado. Además se guarda quién hizo cada cambio y cuándo (historial_repuesto_ot).
-- Idempotente; lo aplica el despliegue (cargar-datos.sh). Debe ir después de 2026-10-26-estados-ot-nuevos-e-historial.sql
-- (usa la fase «eliminada»). Las filas que ya existían no tenían cantidad: se migran con 1 unidad y el estado que
-- corresponde al de su orden (pendiente: reservado; en curso o en revisión: entregado; cerrada: descontado, sin generar
-- movimiento de stock porque el stock de entonces ya se había manejado a mano; eliminada: liberado).
-- Si hubiera el mismo repuesto repetido en una orden, el cambio se detiene con un mensaje claro en lugar de elegir cuál conservar.

BEGIN;

ALTER TABLE operativo.ot_repuesto
    ADD COLUMN IF NOT EXISTS cantidad integer NOT NULL DEFAULT 1,
    ADD COLUMN IF NOT EXISTS estado character varying(12) NOT NULL DEFAULT 'reservado',
    ADD COLUMN IF NOT EXISTS id_movimiento bigint;

DO $reserva$
DECLARE
    repetidos text;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'operativo.ot_repuesto'::regclass AND conname = 'CK_OT_REPUESTO_ESTADO') THEN
        SELECT string_agg('orden ' || id_orden || ' / repuesto ' || id_repuesto, ', ') INTO repetidos
        FROM (SELECT id_orden, id_repuesto FROM operativo.ot_repuesto GROUP BY id_orden, id_repuesto HAVING count(*) > 1) AS d;
        IF repetidos IS NOT NULL THEN
            RAISE EXCEPTION 'Hay repuestos repetidos en una misma orden (%): dejar una sola fila por orden y repuesto antes de aplicar este cambio', repetidos;
        END IF;

        UPDATE operativo.ot_repuesto AS x
        SET estado = CASE actual.fase
                WHEN 'pendiente' THEN 'reservado'
                WHEN 'cerrada' THEN 'descontado'
                WHEN 'eliminada' THEN 'liberado'
                ELSE 'entregado'
            END
        FROM (
            SELECT o.id_orden,
                   (SELECT e.fase
                    FROM operativo.historial_estado_ot AS h
                    JOIN operativo.estado_ot AS e ON e.id_estado_ot = h.id_estado_ot
                    WHERE h.id_orden = o.id_orden
                    ORDER BY h.fecha_hora DESC, h.id_h_estado_ot DESC
                    LIMIT 1) AS fase
            FROM operativo.orden_trabajo AS o
        ) AS actual
        WHERE x.id_orden = actual.id_orden;

        ALTER TABLE operativo.ot_repuesto ADD CONSTRAINT "CK_OT_REPUESTO_ESTADO"
            CHECK (estado IN ('reservado', 'entregado', 'descontado', 'liberado'));
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'operativo.ot_repuesto'::regclass AND conname = 'CK_OT_REPUESTO_CANTIDAD') THEN
        ALTER TABLE operativo.ot_repuesto ADD CONSTRAINT "CK_OT_REPUESTO_CANTIDAD" CHECK (cantidad > 0);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'operativo.ot_repuesto'::regclass AND conname = 'FK_OT_REPUESTO_MOVIMIENTO') THEN
        ALTER TABLE operativo.ot_repuesto ADD CONSTRAINT "FK_OT_REPUESTO_MOVIMIENTO"
            FOREIGN KEY (id_movimiento) REFERENCES operativo.movimiento_stock (id_movimiento);
    END IF;
END
$reserva$;

CREATE UNIQUE INDEX IF NOT EXISTS "UK_OT_REPUESTO_ACTIVO" ON operativo.ot_repuesto (id_orden, id_repuesto) WHERE estado <> 'liberado';
CREATE INDEX IF NOT EXISTS "IX_OT_REPUESTO_COMPROMETIDO" ON operativo.ot_repuesto (id_repuesto) WHERE estado IN ('reservado', 'entregado');

CREATE TABLE IF NOT EXISTS operativo.historial_repuesto_ot (
    id_h_repuesto_ot bigint GENERATED BY DEFAULT AS IDENTITY,
    id_orden bigint NOT NULL,
    id_repuesto bigint NOT NULL,
    accion character varying(12) NOT NULL,
    cantidad_anterior integer,
    cantidad_nueva integer NOT NULL,
    estado_anterior character varying(12),
    estado_nuevo character varying(12) NOT NULL,
    id_usuario bigint,
    fecha_hora timestamp with time zone NOT NULL,
    id_movimiento bigint,
    observacion text,
    CONSTRAINT "PK_HISTORIAL_REPUESTO_OT" PRIMARY KEY (id_h_repuesto_ot),
    CONSTRAINT "FK_HISTORIAL_REPUESTO_OT_ORDEN" FOREIGN KEY (id_orden) REFERENCES operativo.orden_trabajo (id_orden),
    CONSTRAINT "FK_HISTORIAL_REPUESTO_OT_REPUESTO" FOREIGN KEY (id_repuesto) REFERENCES operativo.repuesto (id_repuesto),
    CONSTRAINT "FK_HISTORIAL_REPUESTO_OT_USUARIO" FOREIGN KEY (id_usuario) REFERENCES operativo.usuario (id_usuario),
    CONSTRAINT "FK_HISTORIAL_REPUESTO_OT_MOVIMIENTO" FOREIGN KEY (id_movimiento) REFERENCES operativo.movimiento_stock (id_movimiento),
    CONSTRAINT "CK_HISTORIAL_REPUESTO_OT_ACCION" CHECK (accion IN ('reservar', 'modificar', 'entregar', 'descontar', 'liberar')),
    CONSTRAINT "CK_HISTORIAL_REPUESTO_OT_ESTADO" CHECK (estado_nuevo IN ('reservado', 'entregado', 'descontado', 'liberado')),
    CONSTRAINT "CK_HISTORIAL_REPUESTO_OT_CANTIDAD" CHECK (cantidad_nueva >= 0)
);

CREATE INDEX IF NOT EXISTS "IX_HISTORIAL_REPUESTO_OT_ORDEN_FECHA" ON operativo.historial_repuesto_ot (id_orden, fecha_hora DESC);
CREATE INDEX IF NOT EXISTS "IX_HISTORIAL_REPUESTO_OT_REPUESTO" ON operativo.historial_repuesto_ot (id_repuesto, fecha_hora DESC);

COMMIT;

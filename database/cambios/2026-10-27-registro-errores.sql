-- Errores de API y fallos de sesión, sin cuerpos, credenciales ni tokens.
BEGIN;
CREATE TABLE IF NOT EXISTS operativo.registro_error (
    id_registro_error bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha timestamp with time zone NOT NULL DEFAULT now(),
    origen character varying(20) NOT NULL,
    categoria character varying(160) NOT NULL,
    codigo character varying(80) NOT NULL,
    excepcion character varying(160),
    estado_http integer,
    ruta character varying(250),
    id_correlacion character varying(64),
    CONSTRAINT "CK_REGISTRO_ERROR_ORIGEN" CHECK (origen IN ('api', 'frontend')),
    CONSTRAINT "CK_REGISTRO_ERROR_ESTADO" CHECK (estado_http IS NULL OR estado_http BETWEEN 100 AND 599)
);
CREATE INDEX IF NOT EXISTS "IX_REGISTRO_ERROR_FECHA" ON operativo.registro_error (fecha DESC);
COMMIT;

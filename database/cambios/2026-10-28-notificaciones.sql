-- Notificaciones operativas (RFG-05): avisos dentro de la aplicación por asignación de órdenes, cambios de estado y
-- solicitudes de revisión. Idempotente; lo aplica el despliegue (cargar-datos.sh).
BEGIN;

CREATE TABLE IF NOT EXISTS operativo.notificacion (
    id_notificacion bigint GENERATED BY DEFAULT AS IDENTITY,
    id_usuario bigint NOT NULL,
    id_orden bigint,
    tipo character varying(30) NOT NULL,
    mensaje character varying(300) NOT NULL,
    creada_en timestamp with time zone NOT NULL DEFAULT now(),
    leida_en timestamp with time zone,
    CONSTRAINT "PK_NOTIFICACION" PRIMARY KEY (id_notificacion),
    CONSTRAINT "FK_NOTIFICACION_USUARIO" FOREIGN KEY (id_usuario) REFERENCES operativo.usuario (id_usuario),
    CONSTRAINT "FK_NOTIFICACION_ORDEN" FOREIGN KEY (id_orden) REFERENCES operativo.orden_trabajo (id_orden),
    CONSTRAINT "CK_NOTIFICACION_TIPO" CHECK (tipo IN ('orden_asignada', 'orden_cambio_estado', 'orden_en_revision'))
);
CREATE INDEX IF NOT EXISTS "IX_NOTIFICACION_USUARIO_FECHA" ON operativo.notificacion (id_usuario, creada_en DESC);
CREATE INDEX IF NOT EXISTS "IX_NOTIFICACION_NO_LEIDAS" ON operativo.notificacion (id_usuario) WHERE leida_en IS NULL;

COMMIT;

-- Nuevos estados de las órdenes de trabajo: pendiente, en progreso, en revisión, cerrado, pausado y eliminado (baja
-- lógica), y un historial que guarda de qué estado a qué estado se pasó, cuándo y quién lo hizo (más el motivo).
-- La asignación o el cambio de técnico se guarda aparte, en historial_tecnico_ot, para poder medir las
-- reasignaciones sin mezclarlas con los tiempos por estado. Idempotente; lo aplica el despliegue (cargar-datos.sh).
--
-- Equivalencias de los estados existentes (se conservan los identificadores, así el historial no se rompe):
--   creada y asignada -> pendiente      en_ejecucion -> en_progreso     finalizada -> en_revision
--   cerrada -> cerrado                  pausada -> pausado              cancelada -> eliminado
-- «asignada» deja de ser un estado: tener técnico no cambia el estado de la orden.
-- Los cambios anteriores a este no registran quién los hizo (id_usuario queda vacío).

BEGIN;

ALTER TABLE operativo.historial_estado_ot
    ADD COLUMN IF NOT EXISTS id_estado_anterior bigint,
    ADD COLUMN IF NOT EXISTS id_usuario bigint;

DO $historial$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'operativo.historial_estado_ot'::regclass AND conname = 'FK_HISTORIAL_ESTADO_OT_ANTERIOR') THEN
        ALTER TABLE operativo.historial_estado_ot ADD CONSTRAINT "FK_HISTORIAL_ESTADO_OT_ANTERIOR"
            FOREIGN KEY (id_estado_anterior) REFERENCES operativo.estado_ot (id_estado_ot);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'operativo.historial_estado_ot'::regclass AND conname = 'FK_HISTORIAL_ESTADO_OT_USUARIO') THEN
        ALTER TABLE operativo.historial_estado_ot ADD CONSTRAINT "FK_HISTORIAL_ESTADO_OT_USUARIO"
            FOREIGN KEY (id_usuario) REFERENCES operativo.usuario (id_usuario);
    END IF;
END
$historial$;

CREATE INDEX IF NOT EXISTS "IX_HISTORIAL_ESTADO_OT_ANTERIOR" ON operativo.historial_estado_ot (id_estado_anterior);
CREATE INDEX IF NOT EXISTS "IX_HISTORIAL_ESTADO_OT_USUARIO" ON operativo.historial_estado_ot (id_usuario);

CREATE TABLE IF NOT EXISTS operativo.historial_tecnico_ot (
    id_h_tecnico_ot bigint GENERATED BY DEFAULT AS IDENTITY,
    id_orden bigint NOT NULL,
    id_tecnico_anterior bigint,
    id_tecnico_nuevo bigint,
    id_usuario bigint,
    fecha_hora timestamp with time zone NOT NULL,
    observacion text,
    CONSTRAINT "PK_HISTORIAL_TECNICO_OT" PRIMARY KEY (id_h_tecnico_ot),
    CONSTRAINT "FK_HISTORIAL_TECNICO_OT_ORDEN" FOREIGN KEY (id_orden) REFERENCES operativo.orden_trabajo (id_orden),
    CONSTRAINT "FK_HISTORIAL_TECNICO_OT_ANTERIOR" FOREIGN KEY (id_tecnico_anterior) REFERENCES operativo.usuario (id_usuario),
    CONSTRAINT "FK_HISTORIAL_TECNICO_OT_NUEVO" FOREIGN KEY (id_tecnico_nuevo) REFERENCES operativo.usuario (id_usuario),
    CONSTRAINT "FK_HISTORIAL_TECNICO_OT_USUARIO" FOREIGN KEY (id_usuario) REFERENCES operativo.usuario (id_usuario)
);

CREATE INDEX IF NOT EXISTS "IX_HISTORIAL_TECNICO_OT_ORDEN_FECHA" ON operativo.historial_tecnico_ot (id_orden, fecha_hora DESC);
CREATE INDEX IF NOT EXISTS "IX_HISTORIAL_TECNICO_OT_NUEVO" ON operativo.historial_tecnico_ot (id_tecnico_nuevo);

DO $estados$
DECLARE
    id_creada bigint;
    id_asignada bigint;
BEGIN
    SELECT id_estado_ot INTO id_creada FROM operativo.estado_ot WHERE nombre = 'creada';
    IF id_creada IS NULL THEN
        RETURN;
    END IF;
    SELECT id_estado_ot INTO id_asignada FROM operativo.estado_ot WHERE nombre = 'asignada';

    -- Estado anterior de cada cambio ya guardado: el estado del cambio previo de la misma orden.
    UPDATE operativo.historial_estado_ot AS h
    SET id_estado_anterior = previo.anterior
    FROM (
        SELECT id_h_estado_ot,
               LAG(id_estado_ot) OVER (PARTITION BY id_orden ORDER BY fecha_hora, id_h_estado_ot) AS anterior
        FROM operativo.historial_estado_ot
    ) AS previo
    WHERE h.id_h_estado_ot = previo.id_h_estado_ot AND h.id_estado_anterior IS NULL AND previo.anterior IS NOT NULL;

    -- «asignada» se funde en «pendiente» (la que era «creada»).
    IF id_asignada IS NOT NULL THEN
        UPDATE operativo.historial_estado_ot SET id_estado_ot = id_creada WHERE id_estado_ot = id_asignada;
        UPDATE operativo.historial_estado_ot SET id_estado_anterior = id_creada WHERE id_estado_anterior = id_asignada;
    END IF;

    -- Las asignaciones de técnico que no cambiaron el estado pasan al historial de técnicos.
    INSERT INTO operativo.historial_tecnico_ot (id_orden, fecha_hora, observacion)
    SELECT id_orden, fecha_hora, observacion
    FROM operativo.historial_estado_ot
    WHERE id_estado_ot = id_estado_anterior AND observacion LIKE 'Técnico asignado:%'
    ORDER BY id_orden, fecha_hora, id_h_estado_ot;

    DELETE FROM operativo.historial_estado_ot
    WHERE id_estado_ot = id_estado_anterior AND observacion LIKE 'Técnico asignado:%';

    DELETE FROM operativo.transicion_estado_ot;
    IF id_asignada IS NOT NULL THEN
        DELETE FROM operativo.estado_ot WHERE id_estado_ot = id_asignada;
    END IF;

    ALTER TABLE operativo.estado_ot DROP CONSTRAINT IF EXISTS "CK_ESTADO_OT_FASE";
    UPDATE operativo.estado_ot SET orden = orden + 100;

    UPDATE operativo.estado_ot AS e
    SET nombre = v.nombre, descripcion = v.etiqueta, orden = v.orden, fase = v.fase, exige_tecnico = v.exige_tecnico,
        completa_fecha = v.completa_fecha, tono = v.tono, codigo_alerta = v.codigo_alerta, es_inicial = v.es_inicial
    FROM (VALUES
        ('creada', 'pendiente', 'Pendiente', 1, 'pendiente', false, NULL, 'neutro', 'demorada_para_iniciar', true),
        ('en_ejecucion', 'en_progreso', 'En progreso', 2, 'en_curso', true, 'inicio', 'info', NULL, false),
        ('finalizada', 'en_revision', 'En revisión', 3, 'por_validar', false, NULL, 'destacado', NULL, false),
        ('cerrada', 'cerrado', 'Cerrado', 4, 'cerrada', false, 'cierre', 'exito', NULL, false),
        ('pausada', 'pausado', 'Pausado', 5, 'en_curso', false, NULL, 'alerta', 'pausada_demasiado', false),
        ('cancelada', 'eliminado', 'Eliminado', 6, 'eliminada', false, NULL, 'neutro', NULL, false)
    ) AS v(anterior, nombre, etiqueta, orden, fase, exige_tecnico, completa_fecha, tono, codigo_alerta, es_inicial)
    WHERE e.nombre = v.anterior;

    ALTER TABLE operativo.estado_ot ADD CONSTRAINT "CK_ESTADO_OT_FASE"
        CHECK (fase IN ('pendiente', 'en_curso', 'por_validar', 'cerrada', 'eliminada'));
END
$estados$;

-- Ciclo de vida de la sección 13.1 de «Flujo de datos SOTRA.md». Se vuelve a escribir completo: es la fuente de las reglas.
DELETE FROM operativo.transicion_estado_ot;

INSERT INTO operativo.transicion_estado_ot
    (id_estado_origen, id_estado_destino, exige_motivo, puede_tecnico, accion, principal, al_asignar_tecnico)
SELECT origen.id_estado_ot, destino.id_estado_ot, v.exige_motivo, v.puede_tecnico, v.accion, v.principal, false
FROM (VALUES
    ('pendiente', 'en_progreso', false, true, 'Iniciar', true),
    ('pendiente', 'eliminado', true, false, NULL, false),
    ('en_progreso', 'en_revision', false, true, 'Enviar a revisión', true),
    ('en_progreso', 'pausado', true, true, 'Pausar', false),
    ('pausado', 'en_progreso', false, true, 'Reanudar', true),
    ('pausado', 'eliminado', true, false, NULL, false),
    ('en_revision', 'cerrado', false, false, NULL, false),
    ('en_revision', 'pendiente', true, false, NULL, false)
) AS v(origen, destino, exige_motivo, puede_tecnico, accion, principal)
JOIN operativo.estado_ot AS origen ON origen.nombre = v.origen
JOIN operativo.estado_ot AS destino ON destino.nombre = v.destino;

COMMIT;

-- Datos para que los reportes sean útiles: fecha prevista de ejecución como columna propia, tiempo estimado, causa de
-- falla (catálogo), unidad de uso del activo y lectura de uso de la orden con su historial de cambios, costos opcionales,
-- motivo de pausa codificado y reglas configurables de los avisos de ineficiencia.
-- Idempotente; lo aplica el despliegue (cargar-datos.sh). Debe ir después de 2026-10-26-estados-ot-nuevos-e-historial.sql.
-- Si una orden tuviera una fecha prevista ilegible, el cambio se detiene con el error de PostgreSQL en lugar de inventarla.

BEGIN;

-- Fecha prevista de ejecución como columna propia. Hasta ahora se guardaba como texto en la observación del primer
-- registro del historial de estados. Se copia a la columna (si una orden no la tiene, se usa su fecha de creación) y
-- se vacía esa observación para que no se mezcle con las observaciones reales.
ALTER TABLE operativo.orden_trabajo ADD COLUMN IF NOT EXISTS fecha_prevista_ejecucion date;

UPDATE operativo.orden_trabajo AS o
SET fecha_prevista_ejecucion = COALESCE(
    (SELECT CASE WHEN h.observacion ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' THEN to_date(h.observacion, 'YYYY-MM-DD') END
     FROM operativo.historial_estado_ot AS h
     WHERE h.id_orden = o.id_orden
     ORDER BY h.fecha_hora, h.id_h_estado_ot
     LIMIT 1),
    (o.fecha_creada AT TIME ZONE 'UTC')::date)
WHERE o.fecha_prevista_ejecucion IS NULL;

UPDATE operativo.historial_estado_ot AS h
SET observacion = NULL
WHERE h.observacion ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'
  AND h.id_h_estado_ot = (SELECT p.id_h_estado_ot FROM operativo.historial_estado_ot AS p
                          WHERE p.id_orden = h.id_orden ORDER BY p.fecha_hora, p.id_h_estado_ot LIMIT 1);

ALTER TABLE operativo.orden_trabajo ALTER COLUMN fecha_prevista_ejecucion SET NOT NULL;
CREATE INDEX IF NOT EXISTS "IX_ORDEN_TRABAJO_FECHA_PREVISTA" ON operativo.orden_trabajo (fecha_prevista_ejecucion);

-- Tiempo estimado, causa de falla y lectura de uso de la orden (todos opcionales).
ALTER TABLE operativo.orden_trabajo
    ADD COLUMN IF NOT EXISTS tiempo_estimado_horas numeric(7,2),
    ADD COLUMN IF NOT EXISTS id_causa_falla bigint,
    ADD COLUMN IF NOT EXISTS lectura_uso numeric(12,1);

CREATE TABLE IF NOT EXISTS operativo.causa_falla (
    id_causa_falla bigint GENERATED BY DEFAULT AS IDENTITY,
    nombre character varying(80) NOT NULL,
    estado boolean NOT NULL DEFAULT true,
    CONSTRAINT "PK_CAUSA_FALLA" PRIMARY KEY (id_causa_falla)
);
CREATE UNIQUE INDEX IF NOT EXISTS "UK_CAUSA_FALLA_NOMBRE" ON operativo.causa_falla (lower(nombre));

INSERT INTO operativo.causa_falla (nombre)
SELECT v.nombre
FROM (VALUES ('Hidráulica'), ('Eléctrica'), ('Motor'), ('Transmisión'), ('Neumáticos y rodado'), ('Estructura'), ('Desgaste normal'), ('Otra')) AS v (nombre)
WHERE NOT EXISTS (SELECT 1 FROM operativo.causa_falla AS c WHERE lower(c.nombre) = lower(v.nombre));

DO $datos_reportes$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'operativo.orden_trabajo'::regclass AND conname = 'FK_ORDEN_TRABAJO_CAUSA_FALLA') THEN
        ALTER TABLE operativo.orden_trabajo
            ADD CONSTRAINT "FK_ORDEN_TRABAJO_CAUSA_FALLA" FOREIGN KEY (id_causa_falla) REFERENCES operativo.causa_falla (id_causa_falla),
            ADD CONSTRAINT "CK_ORDEN_TRABAJO_TIEMPO_ESTIMADO" CHECK (tiempo_estimado_horas IS NULL OR (tiempo_estimado_horas > 0 AND tiempo_estimado_horas <= 10000)),
            ADD CONSTRAINT "CK_ORDEN_TRABAJO_LECTURA_USO" CHECK (lectura_uso IS NULL OR lectura_uso >= 0);
    END IF;
END
$datos_reportes$;

CREATE INDEX IF NOT EXISTS "IX_ORDEN_TRABAJO_CAUSA_FALLA" ON operativo.orden_trabajo (id_causa_falla) WHERE id_causa_falla IS NOT NULL;

-- Unidad de uso de cada activo (horas con horómetro o kilómetros con odómetro) y registro de cada cambio de la lectura.
ALTER TABLE operativo.activo ADD COLUMN IF NOT EXISTS unidad_uso character varying(10) NOT NULL DEFAULT 'horas';

CREATE TABLE IF NOT EXISTS operativo.historial_lectura_uso_ot (
    id_h_lectura_uso_ot bigint GENERATED BY DEFAULT AS IDENTITY,
    id_orden bigint NOT NULL,
    lectura_anterior numeric(12,1),
    lectura_nueva numeric(12,1),
    id_usuario bigint,
    fecha_hora timestamp with time zone NOT NULL,
    CONSTRAINT "PK_HISTORIAL_LECTURA_USO_OT" PRIMARY KEY (id_h_lectura_uso_ot),
    CONSTRAINT "FK_HISTORIAL_LECTURA_USO_OT_ORDEN" FOREIGN KEY (id_orden) REFERENCES operativo.orden_trabajo (id_orden),
    CONSTRAINT "FK_HISTORIAL_LECTURA_USO_OT_USUARIO" FOREIGN KEY (id_usuario) REFERENCES operativo.usuario (id_usuario)
);
CREATE INDEX IF NOT EXISTS "IX_HISTORIAL_LECTURA_USO_OT_ORDEN" ON operativo.historial_lectura_uso_ot (id_orden, fecha_hora DESC);

-- Costos opcionales: por hora de parada del tipo de máquina y unitario del repuesto.
ALTER TABLE operativo.tipo_maquina ADD COLUMN IF NOT EXISTS costo_hora_parada numeric(12,2);
ALTER TABLE operativo.repuesto ADD COLUMN IF NOT EXISTS costo_unitario numeric(12,2);

DO $datos_reportes_2$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'operativo.activo'::regclass AND conname = 'CK_ACTIVO_UNIDAD_USO') THEN
        ALTER TABLE operativo.activo
            ADD CONSTRAINT "CK_ACTIVO_UNIDAD_USO" CHECK (unidad_uso IN ('horas', 'kilometros'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'operativo.tipo_maquina'::regclass AND conname = 'CK_TIPO_MAQUINA_COSTO_HORA_PARADA') THEN
        ALTER TABLE operativo.tipo_maquina
            ADD CONSTRAINT "CK_TIPO_MAQUINA_COSTO_HORA_PARADA" CHECK (costo_hora_parada IS NULL OR costo_hora_parada >= 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'operativo.repuesto'::regclass AND conname = 'CK_REPUESTO_COSTO_UNITARIO') THEN
        ALTER TABLE operativo.repuesto
            ADD CONSTRAINT "CK_REPUESTO_COSTO_UNITARIO" CHECK (costo_unitario IS NULL OR costo_unitario >= 0);
    END IF;
END
$datos_reportes_2$;

-- Motivo de pausa codificado: se usa el catálogo motivo_estado_ot, que existía sin asignarse.
ALTER TABLE operativo.motivo_estado_ot ADD COLUMN IF NOT EXISTS codigo character varying(30);
CREATE UNIQUE INDEX IF NOT EXISTS "UK_MOTIVO_ESTADO_OT_CODIGO" ON operativo.motivo_estado_ot (codigo) WHERE codigo IS NOT NULL;

INSERT INTO operativo.motivo_estado_ot (descripcion, codigo)
SELECT v.descripcion, v.codigo
FROM (VALUES ('Falta de repuesto', 'falta_repuesto'), ('Esperando autorización', 'esperando_autorizacion'),
             ('Esperando al cliente', 'esperando_cliente'), ('Otro motivo', 'otro')) AS v (descripcion, codigo)
WHERE NOT EXISTS (SELECT 1 FROM operativo.motivo_estado_ot AS m WHERE m.codigo = v.codigo);

-- Reglas de los avisos de ineficiencia: umbrales configurables, sin mínimos ni máximos fijos.
CREATE TABLE IF NOT EXISTS operativo.regla_aviso (
    codigo character varying(30) NOT NULL,
    nombre character varying(120) NOT NULL,
    activa boolean NOT NULL DEFAULT true,
    umbral numeric(12,2) NOT NULL,
    umbral_critico numeric(12,2),
    ventana_dias integer,
    ventana_critica_dias integer,
    minimo_datos integer NOT NULL DEFAULT 1,
    CONSTRAINT "PK_REGLA_AVISO" PRIMARY KEY (codigo),
    CONSTRAINT "CK_REGLA_AVISO_MINIMO" CHECK (minimo_datos >= 0)
);

INSERT INTO operativo.regla_aviso (codigo, nombre, activa, umbral, umbral_critico, ventana_dias, ventana_critica_dias, minimo_datos)
VALUES
    ('R1', 'Máquina que reincide', true, 2, 3, 180, 730, 1),
